export type IconName = keyof typeof ICONS;

export function Icon({ name, size = 18, className, strokeWidth = 1.9 }: { name: IconName | string; size?: number; className?: string; strokeWidth?: number }) {
  const C = (ICONS as Record<string, LucideIcon>)[name] ?? Box;
  return <C size={size} strokeWidth={strokeWidth} className={className} aria-hidden focusable={false} />;
}
